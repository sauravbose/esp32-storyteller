"""
Make an 8x16 bitmap font for the storyteller's screen.

Draws every printable ASCII character (space to ~) from a monospaced
TrueType font into an 8x16 pixel grid, turns each pixel on or off, and
writes the result as a C header file the ESP32 program can #include.

You only need this if you want to change the font. The repo already
includes the generated font8x16.h.

Usage:
    pip install pillow
    python3 tools/make_font.py PATH/TO/DejaVuSansMono.ttf main/font8x16.h

Optional: also save a big preview image of all the characters:
    python3 tools/make_font.py PATH/TO/DejaVuSansMono.ttf main/font8x16.h --preview preview.png

DejaVu Sans Mono is free (Bitstream Vera / DejaVu licence):
https://github.com/dejavu-fonts/dejavu-fonts/releases
Any monospaced .ttf works; try different sizes with --size.
"""

import argparse

from PIL import Image, ImageDraw, ImageFont

WIDTH, HEIGHT = 8, 16   # size of each character cell, in pixels
FIRST, LAST = 32, 126   # printable ASCII: space through ~
THRESHOLD = 110         # 0-255: how dark a pixel must be to count as "on"


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("ttf", help="path to a monospaced .ttf font")
    parser.add_argument("out", help="where to write the C header, e.g. main/font8x16.h")
    parser.add_argument("--size", type=int, default=13, help="font size in points (default 13)")
    parser.add_argument("--preview", help="optional PNG file to save a preview into")
    args = parser.parse_args()

    font = ImageFont.truetype(args.ttf, args.size)
    ascent, descent = font.getmetrics()
    baseline_y = HEIGHT - ascent - descent + 1  # nudges letters so tails fit in the cell

    chars = []
    preview = Image.new("L", (WIDTH * 32, HEIGHT * 3), 0)
    for i, code in enumerate(range(FIRST, LAST + 1)):
        # 1. Draw the character in white on a tiny black 8x16 image.
        cell = Image.new("L", (WIDTH, HEIGHT), 0)
        ImageDraw.Draw(cell).text((0, baseline_y), chr(code), font=font, fill=255)

        # 2. Each row of 8 pixels becomes one byte: bit 7 = leftmost pixel.
        rows = []
        for y in range(HEIGHT):
            byte = 0
            for x in range(WIDTH):
                if cell.getpixel((x, y)) > THRESHOLD:
                    byte |= 0x80 >> x
            rows.append(byte)
        chars.append((code, rows))

        on_off = cell.point(lambda p: 255 if p > THRESHOLD else 0)
        preview.paste(on_off, ((i % 32) * WIDTH, (i // 32) * HEIGHT))

    # 3. Write all characters out as a C array.
    with open(args.out, "w") as f:
        f.write("// 8x16 bitmap font, ASCII 32-126, generated by tools/make_font.py\n")
        f.write("// Each character is 16 rows; each row is one byte, leftmost pixel = top bit.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define FONT_W {WIDTH}\n#define FONT_H {HEIGHT}\n\n")
        f.write(f"static const uint8_t font8x16[{LAST - FIRST + 1}][{HEIGHT}] = {{\n")
        for code, rows in chars:
            label = {"\\": "backslash", "'": "quote"}.get(chr(code), chr(code))
            f.write("    {" + ", ".join(f"0x{b:02X}" for b in rows) + f"}},  // {label}\n")
        f.write("};\n")
    print(f"Wrote {len(chars)} characters to {args.out}")

    if args.preview:
        preview.resize((preview.width * 4, preview.height * 4), Image.NEAREST).save(args.preview)
        print(f"Saved preview to {args.preview}")


if __name__ == "__main__":
    main()
